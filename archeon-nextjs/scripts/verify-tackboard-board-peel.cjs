/* Verifies pinboard boundary geometry, peel implementation and minimal CSS invariants. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const geometry = fs.readFileSync(path.join(root, 'src/features/tackboard/workspaceGeometry.ts'), 'utf8');
const transpiled = ts.transpileModule(geometry, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 }, reportDiagnostics: true });
assert.equal(transpiled.diagnostics?.filter(d => d.category === ts.DiagnosticCategory.Error).length, 0);
const moduleRef = { exports: {} };
vm.runInNewContext(transpiled.outputText, { module: moduleRef, exports: moduleRef.exports }, { timeout: 1000 });
const { workspaceDimensions, clampNotePosition, draggedNotePosition } = moduleRef.exports;
const canvas = workspaceDimensions([{x:20,y:25,width:247,height:540},{x:1700,y:1200,width:247,height:380}]);
assert.ok(canvas.width >= 1983 && canvas.height >= 1616, 'canvas fits tall, distant notes with a tight paper margin');
const inside = clampNotePosition({x:-500,y:Infinity}, {width:1000,height:700}, {width:247,height:265});
assert.equal(inside.x,18);assert.equal(inside.y,18);
const max = clampNotePosition({x:9000,y:9000}, {width:1000,height:700},{width:247,height:265});
assert.equal(max.x,735);assert.equal(max.y,417);
const dragged = draggedNotePosition({origin:{x:600,y:400},pointerStart:{x:0,y:0},pointerCurrent:{x:9999,y:9999},scrollStart:{x:0,y:0},scrollCurrent:{x:0,y:0},canvas:{width:1000,height:700},note:{width:247,height:265}});
assert.equal(dragged.x,735);assert.equal(dragged.y,417);
const jsx = fs.readFileSync(path.join(root, 'src/app/app/tackboard/TackboardClient.tsx'), 'utf8');
const tsx = ts.transpileModule(jsx,{fileName:'TackboardClient.tsx',compilerOptions:{jsx:ts.JsxEmit.Preserve,target:ts.ScriptTarget.ES2020},reportDiagnostics:true});
assert.equal(tsx.diagnostics?.filter(d=>d.category===ts.DiagnosticCategory.Error).length,0,'TackBoard TSX parses');
for(const needed of ['flight.animate(', 'document.body.appendChild(flight)', 'peelSourceHidden', 'clampNotePosition(', 'peelFlights.current', 'removePeelFlight(note.id)']) assert.ok(jsx.includes(needed),`missing ${needed}`);
const css=fs.readFileSync(path.join(root,'src/app/app/tackboard/tackboard.module.css'),'utf8');
for(const needed of ['.canvasSection{position:relative;isolation:isolate;', '.overlay{z-index:1000}', '.peelFlight::after', '.peelSourceHidden', 'overflow-y:auto']) assert.ok(css.includes(needed),`missing ${needed}`);
const invoice=fs.readFileSync(path.join(root,'src/app/app/invoice/invoice.css'),'utf8');
assert.ok(invoice.includes('--invoice-bg:#05080d') && invoice.includes('background:#070d16'), 'midnight invoice theme included');
console.log('PASS: clamping, tall-board bounds, pointer drag bounds, peel layer, invoice palette, TSX syntax');
