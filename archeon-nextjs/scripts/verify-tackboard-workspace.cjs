/** Regression checks for the draggable, scrollable board. Run: node scripts/verify-tackboard-workspace.cjs */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const geometry = fs.readFileSync(path.join(root, 'src/features/tackboard/workspaceGeometry.ts'), 'utf8');
const compiled = ts.transpileModule(geometry, {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const moduleObj={exports:{}};
vm.runInNewContext(compiled,{module:moduleObj,exports:moduleObj.exports}, {filename:'workspaceGeometry.js'});
const {workspaceDimensions,edgeScrollVelocity,draggedNotePosition,dragCanvasDimensions,nextNotePosition}=moduleObj.exports;

assert.equal(workspaceDimensions([], {width:960,height:580}).width,560, 'empty paper is compact and centered');
assert.equal(workspaceDimensions([], {width:960,height:580}).height,410, 'empty paper is compact vertically');
assert.equal(workspaceDimensions([{x:26,y:28,width:247,height:265}], {width:960,height:580}).width,560, 'one note does not create extra horizontal scroll');
assert.equal(workspaceDimensions([{x:26,y:28,width:247,height:265}], {width:960,height:580}).height,410, 'one note does not create extra vertical scroll');
assert.equal(workspaceDimensions([],{width:350,height:330}).width,350, 'empty canvas adapts to small screens');
assert.equal(workspaceDimensions([],{width:350,height:330}).height,330, 'empty canvas adapts vertically');
assert.equal(workspaceDimensions([{x:1650,y:1300}]).width,1933);
assert.equal(workspaceDimensions([{x:1650,y:1300}]).height,1601);
assert.equal(workspaceDimensions([{x:80,y:120,width:247,height:265}],{width:340,height:400}).width,363, 'board grows only just beyond note');
assert.equal(workspaceDimensions([{x:80,y:120,width:247,height:265}],{width:340,height:400}).height,421);
assert.deepEqual(JSON.parse(JSON.stringify(nextNotePosition([], {width:400,height:500,scrollLeft:0,scrollTop:0}))),{x:26,y:28});
assert.deepEqual(JSON.parse(JSON.stringify(nextNotePosition([{x:26,y:28,width:247,height:265}], {width:400,height:500,scrollLeft:0,scrollTop:0}))),{x:26,y:340});
assert.deepEqual(JSON.parse(JSON.stringify(nextNotePosition([], {width:400,height:500,scrollLeft:900,scrollTop:600}))),{x:926,y:628});
assert.deepEqual(JSON.parse(JSON.stringify(dragCanvasDimensions({width:900,height:650},{width:900,height:650,scrollLeft:0,scrollTop:0},{x:13,y:0}))),{width:1200,height:650});
assert.deepEqual(JSON.parse(JSON.stringify(dragCanvasDimensions({width:1500,height:1000},{width:900,height:650,scrollLeft:0,scrollTop:0},{x:13,y:13}))),{width:1500,height:1000});
const rect={left:100,right:700,top:200,bottom:800};
assert.deepEqual(JSON.parse(JSON.stringify(edgeScrollVelocity(120,780,rect))),{x:-13,y:13});
assert.deepEqual(JSON.parse(JSON.stringify(edgeScrollVelocity(400,500,rect))),{x:0,y:0});
const base={origin:{x:100,y:100},pointerStart:{x:200,y:200},pointerCurrent:{x:300,y:260},scrollStart:{x:0,y:0},scrollCurrent:{x:150,y:75},canvas:{width:1500,height:1050},note:{width:247,height:260}};
assert.deepEqual(JSON.parse(JSON.stringify(draggedNotePosition(base))),{x:350,y:235});
assert.deepEqual(JSON.parse(JSON.stringify(draggedNotePosition({...base,layoutShift:{x:140,y:90}}))),{x:490,y:325},'drag stays under pointer when centered canvas grows');
assert.deepEqual(JSON.parse(JSON.stringify(draggedNotePosition({...base,pointerCurrent:{x:-10000,y:-10000}}))),{x:18,y:18});
assert.deepEqual(JSON.parse(JSON.stringify(draggedNotePosition({...base,pointerCurrent:{x:99999,y:99999}}))),{x:1235,y:772});

const client=fs.readFileSync(path.join(root,'src/app/app/tackboard/TackboardClient.tsx'),'utf8');
const styles=fs.readFileSync(path.join(root,'src/app/app/tackboard/tackboard.module.css'),'utf8');
assert.match(client,/onPointerDown=\{e => dragStart\(e,note\)\}/);
assert.match(client,/onPointerDownCapture=\{\(\) => setFrontNoteId\(note.id\)\}/);
assert.match(client,/data-note-action="true"/);
assert.match(client,/onClick=\{toggleBoardFocus\}/);
assert.match(client,/className=\{styles.boardNewNoteButton\} onClick=\{startNote\}/, 'add-note action stays outside the scrolling canvas');
assert.match(client,/ResizeObserver/, 'canvas responds to viewport resizing');
assert.doesNotMatch(client,/styles.addOnCanvas/, 'old far-away add-note tile no longer used');
assert.match(client,/archeon:tackboard:expanded-board/);
assert.match(client,/role="region" aria-label="Scrollable pinboard/);
assert.match(styles,/\.boardViewport\s*\{[^}]*overflow:auto/s);
assert.match(styles,/justify-content:safe center/, 'compact canvas is centered until it overflows');
assert.match(styles,/\.boardFocused \.sidebar\s*\{display:none\}/);
assert.match(styles,/\.noteTop\s*\{[^}]*touch-action:none/s);
console.log('PASS: centered compact empty pinboard, fitted notes, toolbar new-note control, accessible note placement, pointer-correct drag expansion, and layering');
